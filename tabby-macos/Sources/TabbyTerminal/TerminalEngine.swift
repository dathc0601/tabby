import Foundation
import TabbyCore

/// What a terminal pane needs from the emulator view. Port of Tabby's `Frontend`
/// (`tabby-terminal/src/frontends/frontend.ts`). The macOS implementation is
/// `SwiftTermEngine`; tests use a fake.
public protocol TerminalEngine: AnyObject {
    var engineDelegate: TerminalEngineDelegate? { get set }
    var gridSize: (cols: Int, rows: Int) { get }
    var isAlternateScreen: Bool { get }
    var isBracketedPasteMode: Bool { get }
    var hasSelection: Bool { get }

    /// Output from the session.
    func feed(_ data: Data)
    func selectedText() -> String?
    func selectAll()
    func clearSelection()
    /// ⌘K: clear the screen and scrollback.
    func clearBuffer()
    /// Plain-text snapshot of scrollback + screen, used for tab recovery.
    func snapshotText(maxLines: Int) -> String
    func scroll(_ action: TerminalScrollAction)
    func apply(settings: TerminalSettings, scheme: ColorScheme, fontSize: Double)
    func focus()

    func find(_ query: String, options: TerminalSearchOptions, backwards: Bool) -> Bool
    func searchSummary(_ query: String, options: TerminalSearchOptions) -> (index: Int, total: Int)
    func clearSearch()
}

public protocol TerminalEngineDelegate: AnyObject {
    /// Bytes typed by the user (or generated by the emulator) for the session.
    func engine(_ engine: TerminalEngine, send data: Data)
    func engine(_ engine: TerminalEngine, resized cols: Int, rows: Int)
    func engine(_ engine: TerminalEngine, titleChanged title: String)
    func engine(_ engine: TerminalEngine, directoryChanged directory: String?)
    func engineBell(_ engine: TerminalEngine)
    func engineDidFocus(_ engine: TerminalEngine)
    /// The user chose Paste (menu, ⌘V, middle click); the pane decides how to send it.
    func engine(_ engine: TerminalEngine, paste text: String)
    func engineSelectionChanged(_ engine: TerminalEngine)
}

public enum TerminalScrollAction: Equatable, Sendable {
    case top, bottom, pageUp, pageDown, lineUp, lineDown
}

public struct TerminalSearchOptions: Equatable, Sendable {
    public var caseSensitive: Bool
    public var regex: Bool
    public var wholeWord: Bool

    public init(caseSensitive: Bool = false, regex: Bool = false, wholeWord: Bool = false) {
        self.caseSensitive = caseSensitive
        self.regex = regex
        self.wholeWord = wholeWord
    }
}
