import Foundation

/// Turns an SSH profile (plus its jump-host chain) into an `ssh_config` file for the system
/// OpenSSH client. This is the phase-1 SSH backend: `ssh -F <file> <alias>` runs inside a
/// PTY, and prompts go through the askpass helper. See docs/ARCHITECTURE.md.
public struct SSHConfigGenerator {
    public struct Paths: Sendable {
        /// The app's own known_hosts file (new keys are written here).
        public var knownHostsFile: String
        /// Additional known_hosts files that are read (e.g. `~/.ssh/known_hosts`).
        public var extraKnownHostsFiles: [String]
        /// Directory for ControlMaster sockets. Keep it short: socket paths are limited to 104 bytes.
        public var controlDirectory: String
        /// Command run by ssh after authentication succeeds (askpass helper in "connected" mode).
        public var localCommand: String?
        /// Private keys that arrived through sync, used when a key file is missing here.
        public var syncedKeys: SyncedKeys
        /// Whether a key file exists here (injected by tests so they never look at ~/.ssh).
        public var fileExists: @Sendable (String) -> Bool

        public init(knownHostsFile: String, extraKnownHostsFiles: [String] = [], controlDirectory: String, localCommand: String? = nil,
                    syncedKeys: SyncedKeys = .none,
                    fileExists: @escaping @Sendable (String) -> Bool = { FileManager.default.fileExists(atPath: $0) }) {
            self.knownHostsFile = knownHostsFile
            self.extraKnownHostsFiles = extraKnownHostsFiles
            self.controlDirectory = controlDirectory
            self.localCommand = localCommand
            self.syncedKeys = syncedKeys
            self.fileExists = fileExists
        }
    }

    public struct Output: Equatable, Sendable {
        public var config: String
        /// The Host alias to pass to `ssh`.
        public var alias: String
    }

    public enum GeneratorError: Error, Equatable, LocalizedError {
        case missingHost
        case jumpHostLoop(String)

        public var errorDescription: String? {
            switch self {
            case .missingHost: return L("The SSH profile has no host.")
            case .jumpHostLoop(let id): return L("Jump host chain loops back to {id}.", ["id": id])
            }
        }
    }

    public var paths: Paths
    public var verifyHostKeys: Bool

    public init(paths: Paths, verifyHostKeys: Bool = true) {
        self.paths = paths
        self.verifyHostKeys = verifyHostKeys
    }

    /// - Parameters:
    ///   - options: the target's options.
    ///   - jumpHostResolver: resolves a `jumpHost` profile id to that profile's options.
    public func generate(_ options: SSHOptions, jumpHostResolver: (String) -> SSHOptions?) throws -> Output {
        guard !options.host.isEmpty else { throw GeneratorError.missingHost }
        var blocks: [String] = []
        var visited: Set<String> = []

        // Resolve the chain: target -> its jump host -> that host's jump host -> ...
        var hops: [(id: String, options: SSHOptions)] = []
        var next = options.jumpHost
        while let id = next {
            guard !visited.contains(id) else { throw GeneratorError.jumpHostLoop(id) }
            visited.insert(id)
            guard let hop = jumpHostResolver(id) else { break }
            hops.append((id, hop))
            next = hop.jumpHost
        }

        // hops[0] is the closest to the target; the last one is reached first.
        for (index, hop) in hops.enumerated() {
            let parent = index + 1 < hops.count ? "tabby-hop-\(index + 1)" : nil
            blocks.append(block(alias: "tabby-hop-\(index)", hop.options, proxyJump: parent, isTarget: false))
        }
        let targetAlias = "tabby-target"
        blocks.insert(block(alias: targetAlias, options, proxyJump: hops.isEmpty ? nil : "tabby-hop-0", isTarget: true), at: 0)
        let header = "# Generated by TabbyMac for one session. Do not edit.\n" // l10n-ignore: ssh_config text and ssh's own output
        return Output(config: header + blocks.joined(separator: "\n"), alias: targetAlias)
    }

    func block(alias: String, _ o: SSHOptions, proxyJump: String?, isTarget: Bool) -> String {
        var lines: [String] = ["Host \(alias)"] // l10n-ignore: ssh_config syntax
        func add(_ key: String, _ value: String) { lines.append("    \(key) \(value)") }

        add("HostName", Self.quote(o.host))
        add("Port", String(o.port)) // l10n-ignore: ssh_config syntax
        if !o.user.isEmpty { add("User", Self.quote(o.user)) } // l10n-ignore: ssh_config syntax

        let keys = o.privateKeys.isEmpty
            ? paths.syncedKeys.identitiesForProfileWithoutKeys(fileExists: paths.fileExists)
            : o.privateKeys.map { paths.syncedKeys.resolve($0, fileExists: paths.fileExists) }
        for key in keys {
            add("IdentityFile", Self.quote(Self.normalizeKeyPath(key)))
        }
        switch o.auth {
        case .password?:
            add("PreferredAuthentications", "password,keyboard-interactive")
            add("PubkeyAuthentication", "no")
        case .publicKey?:
            add("PreferredAuthentications", "publickey")
            if !o.privateKeys.isEmpty { add("IdentitiesOnly", "yes") }
        case .agent?:
            add("PreferredAuthentications", "publickey")
        case .keyboardInteractive?:
            add("PreferredAuthentications", "keyboard-interactive")
        case nil:
            break
        }

        if o.keepaliveInterval > 0 {
            add("ServerAliveInterval", String(max(1, o.keepaliveInterval / 1000)))
            add("ServerAliveCountMax", String(max(1, o.keepaliveCountMax)))
        }
        if let t = o.readyTimeout, t > 0 { add("ConnectTimeout", String(max(1, t / 1000))) }
        if isTarget && o.x11 { add("ForwardX11", "yes") }
        if isTarget && o.agentForward { add("ForwardAgent", "yes") }
        if isTarget && o.skipBanner { add("LogLevel", "ERROR") }

        if let proxyJump {
            add("ProxyJump", proxyJump)
        } else if let pc = o.proxyCommand {
            add("ProxyCommand", pc)
        } else if let socks = o.socksProxyHost, let port = o.socksProxyPort {
            add("ProxyCommand", "/usr/bin/nc -X 5 -x \(socks):\(port) %h %p")
        } else if let http = o.httpProxyHost, let port = o.httpProxyPort {
            add("ProxyCommand", "/usr/bin/nc -X connect -x \(http):\(port) %h %p")
        }

        if isTarget {
            for f in o.forwardedPorts {
                let listen = "\(Self.bracket(f.host)):\(f.port)"
                switch f.type {
                case .local: add("LocalForward", "\(listen) \(Self.bracket(f.targetAddress)):\(f.targetPort)")
                case .remote: add("RemoteForward", "\(listen) \(Self.bracket(f.targetAddress)):\(f.targetPort)")
                case .dynamic: add("DynamicForward", listen)
                }
            }
            if !o.forwardedPorts.isEmpty { add("ExitOnForwardFailure", "no") }
            if o.reuseSession {
                add("ControlMaster", "auto")
                add("ControlPath", Self.quote(paths.controlDirectory + "/%C"))
                add("ControlPersist", "10s")
            }
            if let lc = paths.localCommand {
                add("PermitLocalCommand", "yes")
                add("LocalCommand", lc)
            }
        }

        let knownHosts = ([paths.knownHostsFile] + paths.extraKnownHostsFiles).map(Self.quote).joined(separator: " ")
        add("UserKnownHostsFile", knownHosts)
        add("StrictHostKeyChecking", verifyHostKeys ? "ask" : "no")
        add("HashKnownHosts", "no")
        return lines.joined(separator: "\n") + "\n"
    }

    /// Tabby stores key paths either as plain paths or as `file://` URLs.
    static func normalizeKeyPath(_ key: String) -> String {
        if key.hasPrefix("file://"), let url = URL(string: key) { return url.path }
        if key.hasPrefix("~/") { return NSHomeDirectory() + String(key.dropFirst(1)) }
        return key
    }

    static func quote(_ s: String) -> String {
        s.contains(where: { $0 == " " || $0 == "\t" || $0 == "#" }) ? "\"\(s.replacingOccurrences(of: "\"", with: ""))\"" : s
    }

    static func bracket(_ host: String) -> String {
        host.contains(":") && !host.hasPrefix("[") ? "[\(host)]" : (host.isEmpty ? "localhost" : host)
    }
}

/// Classifies the prompts OpenSSH sends to `SSH_ASKPASS`, so the app can answer from the
/// Keychain or show the right native sheet.
public enum AskpassPrompt: Equatable, Sendable {
    case password(user: String, host: String)
    case passphrase(keyPath: String)
    case hostKey(host: String, keyType: String?, fingerprint: String?, message: String)
    case hostKeyChanged(message: String)
    case confirm(message: String)
    case information(message: String)
    case secret(message: String)

    /// - Parameters:
    ///   - prompt: the prompt text ssh passed as argv[1].
    ///   - kind: the `SSH_ASKPASS_PROMPT` value (`confirm`, `none`, or empty).
    public static func classify(_ prompt: String, kind: String?) -> AskpassPrompt {
        let p = prompt.trimmingCharacters(in: .whitespacesAndNewlines)
        if p.contains("REMOTE HOST IDENTIFICATION HAS CHANGED") {
            return .hostKeyChanged(message: p)
        }
        if p.contains("The authenticity of host") || p.contains("Are you sure you want to continue connecting") { // l10n-ignore: ssh's own output
            let host = firstMatch(#"authenticity of host '([^']+)'"#, in: p) ?? "" // l10n-ignore: ssh_config text and ssh's own output
            let keyType = firstMatch(#"([A-Z0-9-]+) key fingerprint is"#, in: p) // l10n-ignore: ssh_config text and ssh's own output
            let fp = firstMatch(#"(SHA256:[A-Za-z0-9+/=]+|MD5:[0-9a-f:]+)"#, in: p)
            return .hostKey(host: host, keyType: keyType, fingerprint: fp, message: p)
        }
        if let m = matches(#"^\(?([^()@\s]+)@([^()\s']+)\)?(?:'s)? [Pp]assword: ?$"#, in: p), m.count == 2 {
            return .password(user: m[0], host: m[1])
        }
        if let key = firstMatch(#"^Enter passphrase for (?:key )?'?([^']+?)'?: ?$"#, in: p) { // l10n-ignore: ssh_config text and ssh's own output
            return .passphrase(keyPath: key)
        }
        switch kind?.lowercased() {
        case "confirm": return .confirm(message: p)
        case "none": return .information(message: p)
        default: return .secret(message: p)
        }
    }

    static func matches(_ pattern: String, in s: String) -> [String]? {
        guard let re = try? NSRegularExpression(pattern: pattern),
              let m = re.firstMatch(in: s, range: NSRange(s.startIndex..., in: s)) else { return nil }
        return (1..<m.numberOfRanges).compactMap { i in Range(m.range(at: i), in: s).map { String(s[$0]) } }
    }

    static func firstMatch(_ pattern: String, in s: String) -> String? {
        matches(pattern, in: s)?.first
    }
}
